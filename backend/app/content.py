def team_posts(team: int) -> list[int]:
    # 20 shared examples and 40 rotating examples: 60 unique posts per team.
    return list(range(20)) + [20 + ((team * 26 + i) % 80) for i in range(40)]


def assigned_posts(team: int, seat: int) -> list[int]:
    pool = team_posts(team)
    # Everyone labels 8 anchors plus one of 5 rotating batches. Reuse batches
    # for larger teams so later arrivals still have a full, distinct-post queue.
    return pool[:8] + pool[8 + (seat % 5)::5]

