import { test, expect } from '@playwright/test'

test('instructor opens a room and a mobile student contributes labels', async ({ browser }) => {
  const base = process.env.E2E_BASE_URL || 'http://127.0.0.1:8000'
  const key = process.env.E2E_INSTRUCTOR_SECRET
  if (!key) throw new Error('Set E2E_INSTRUCTOR_SECRET to the running server’s access key.')
  const teacherContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const teacher = await teacherContext.newPage()
  const errors: string[] = []
  teacher.on('pageerror', error => errors.push(error.message))
  await teacher.goto(`${base}/instructor`)
  await teacher.getByLabel('Instructor access key').fill(key)
  await teacher.getByRole('button', { name: 'Create game room' }).click()
  await expect(teacher.getByRole('heading', { name: 'The work behind the model.' })).toBeVisible()
  const code = (await teacher.locator('.room-code').innerText()).trim()
  await expect(teacher.getByText(/Phones cannot reach localhost/)).toBeVisible()
  await expect(teacher.getByRole('button', {name:'Copy join link'})).toBeDisabled()
  await teacher.getByLabel('Student-accessible URL').fill('http://192.168.1.20:8000')
  await expect(teacher.locator('.join-link')).toHaveAttribute('href', `http://192.168.1.20:8000/?room=${code}`)
  await expect(teacher.locator('.room-card > svg')).toBeVisible()
  await expect(teacher.getByRole('button', {name:'Copy join link'})).toBeEnabled()
  await teacher.getByLabel('Student-accessible URL').fill('javascript:alert(1)')
  await expect(teacher.getByRole('button', {name:'Copy join link'})).toBeDisabled()
  await teacher.getByLabel('Student-accessible URL').fill('https://classroom.example.org')
  await expect(teacher.locator('.join-link')).toHaveAttribute('href', `https://classroom.example.org/?room=${code}`)
  const studentContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const student = await studentContext.newPage()
  student.on('pageerror', error => errors.push(error.message))
  await student.goto(`${base}/?room=${code}`)
  await student.getByLabel('Your nickname').fill('Maya')
  await student.getByRole('button', { name: 'Enter the room' }).click()
  await expect(student.getByRole('heading', { name: 'You’re on the team.' })).toBeVisible()
  await expect(teacher.getByText('Maya', { exact: true })).toBeVisible()
  await teacher.getByRole('button', { name: 'Start annotation' }).click()
  await expect(student.getByRole('button', { name: 'Allow', exact: true })).toBeVisible()
  await student.screenshot({ path: 'test-results/student-mobile.png', fullPage: true })
  expect(await student.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await student.getByRole('button', { name: 'Allow', exact: true }).click()
  await expect(student.getByText(/1 \/ \d+ submitted/)).toBeVisible()
  await student.reload()
  await expect(student.getByText(/1 \/ \d+ submitted/)).toBeVisible()
  await expect(teacher.locator('.big-stats strong').first()).toHaveText('1')
  await teacher.getByRole('button', { name: 'Pause shift' }).click()
  await expect(student.getByRole('heading', { name: 'Take a breath. The shift is paused.' })).toBeVisible()
  await teacher.screenshot({ path: 'test-results/instructor-desktop.png', fullPage: true })
  await teacher.getByRole('button', { name: 'Presentation', exact: true }).click()
  await expect(teacher.getByRole('button', { name: 'Exit presentation' })).toBeVisible()
  expect(errors).toEqual([])
  await teacherContext.close()
  await studentContext.close()
})

test('one mobile student can train, invest, compare, and improve without other teams', async ({browser})=>{
  test.setTimeout(90000)
  const base=process.env.E2E_BASE_URL||'http://127.0.0.1:8000'
  const key=process.env.E2E_INSTRUCTOR_SECRET
  if(!key)throw new Error('Set E2E_INSTRUCTOR_SECRET.')
  const teacherContext=await browser.newContext({viewport:{width:1440,height:1000}})
  const teacher=await teacherContext.newPage()
  const errors:string[]=[]
  teacher.on('pageerror',e=>errors.push(e.message))
  await teacher.goto(`${base}/instructor`)
  await teacher.getByLabel('Instructor access key').fill(key)
  await teacher.getByRole('button',{name:'Create game room'}).click()
  const code=(await teacher.locator('.room-code').innerText()).trim()
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  const student=await context.newPage()
  student.on('pageerror',e=>errors.push(e.message))
  student.on('dialog',dialog=>dialog.accept())
  await student.goto(`${base}/?room=${code}`)
  await student.getByLabel('Your nickname').fill('Solo tester')
  await student.getByRole('button',{name:'Enter the room'}).click()
  await expect(student.getByRole('heading',{name:'You’re on the team.'})).toBeVisible()
  await teacher.getByRole('button',{name:'Start annotation'}).click()
  for(let i=0;i<12;i++){
    await student.getByRole('button',{name:i%2===0?'Allow':'Remove',exact:true}).click()
    await expect(student.getByText(new RegExp(`${i+1} / \\d+ submitted`))).toBeVisible()
  }
  await teacher.getByRole('button',{name:'Begin training',exact:true}).click()
  await expect(student.getByRole('heading',{name:'What will your team invest in?'})).toBeVisible()
  await teacher.getByRole('button',{name:'Train eligible teams'}).click()
  await expect(student.getByText(/Run saved · 12 posts/)).toBeVisible()
  await expect(student.getByRole('heading',{name:'Inspect the predictions'})).toHaveCount(0)
  for(const title of ['Additional annotation','Computing investment','Infrastructure upgrade']){
    await student.locator('.purchase-card').filter({has:student.getByRole('heading',{name:title,exact:true})}).getByRole('button').click()
  }
  await expect(student.getByText('0 credits left',{exact:true})).toBeVisible()
  await expect(student.getByText(/12 \/ 29 submitted/)).toBeVisible()
  await student.getByLabel('Model configuration').selectOption('character')
  await expect(student.getByRole('button',{name:'Train model',exact:true})).toBeEnabled()
  await student.getByRole('button',{name:'Train model',exact:true}).click()
  await expect(student.getByText(/Model trained. The instructor/)).toBeVisible()
  expect(await student.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await student.screenshot({path:'test-results/investment-mobile.png',fullPage:true})
  await teacher.getByRole('button',{name:'Compare models'}).click()
  await expect(student.getByRole('heading',{name:'What did your companies learn?'})).toBeVisible()
  await expect(student.getByRole('heading',{name:'No trained model',exact:true})).toHaveCount(2)
  await expect(student.locator('.confusion')).toHaveCount(1)
  await expect(student.locator('.prediction-card')).toHaveCount(20)
  await expect(student.getByRole('button',{name:'Train model',exact:true})).toHaveCount(0)
  await student.reload()
  await expect(student.locator('.confusion')).toHaveCount(1)
  expect(await student.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await student.screenshot({path:'test-results/testing-mobile.png',fullPage:true})
  await teacher.locator('.testing > .team-grid').screenshot({path:'test-results/testing-cards-desktop.png'})
  await student.locator('.score-card').first().screenshot({path:'test-results/testing-card-mobile.png'})
  await teacher.locator('.testing').screenshot({path:'test-results/testing-desktop.png'})
  await student.getByLabel('Prediction filter').selectOption('errors')
  await expect(student.locator('.prediction-card').first()).toBeVisible()
  await teacher.getByRole('button',{name:'Open improvement round'}).click()
  await expect(student.getByRole('heading',{name:'What will your team invest in?'})).toBeVisible()
  await student.getByLabel('Model configuration').selectOption('bigram')
  await expect(student.getByRole('button',{name:'Train model',exact:true})).toBeEnabled()
  await teacher.getByRole('button',{name:'Train eligible teams'}).click()
  // Bulk training on a second round must not reuse the first run's idempotency key.
  await expect(student.locator('.model-saved')).not.toContainText('retrain to apply')
  await teacher.getByRole('button',{name:'Compare models'}).click()
  await expect(student.locator('.score-card').first().getByText(/word pairs/).first()).toBeVisible()
  await student.locator('.score-card').first().getByText('Model limits & run history').click()
  await expect(student.getByText(/Run 3 · Words \+ word pairs/)).toBeVisible()
  await teacher.getByRole('button',{name:'Reveal the hidden infrastructure'}).click()
  await expect(student.getByRole('heading',{name:'Your AI was never alone.'})).toBeVisible()
  await student.getByRole('button',{name:/^Cooling water/}).focus()
  await student.keyboard.press('Enter')
  await expect(student.locator('#node-detail').getByRole('heading',{name:'Cooling water',exact:true})).toBeVisible()
  await expect(student.locator('.reveal-comparison')).toBeVisible()
  expect(await student.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await student.locator('.infrastructure').screenshot({path:'test-results/reveal-mobile.png'})
  teacher.once('dialog',dialog=>dialog.accept(code))
  await teacher.getByRole('button',{name:'Reset room',exact:true}).click()
  await expect(teacher.getByRole('heading',{name:'Your workforce is assembling.'})).toBeVisible()
  await expect(student.getByRole('heading',{name:'You’re on the team.'})).toBeVisible()
  await expect(student.getByText(/0 \/ 19 submitted/)).toBeVisible()
  // Reset preserves the same student session and starts a usable new generation.
  await teacher.getByRole('button',{name:'Start annotation'}).click()
  await student.getByRole('button',{name:'Allow',exact:true}).click()
  await expect(student.getByText(/1 \/ 19 submitted/)).toBeVisible()
  expect(errors).toEqual([])
  await teacherContext.close()
  await context.close()
})

test('a local demonstration trains three models and reveals infrastructure without student devices', async ({browser})=>{
  test.setTimeout(90000)
  const base=process.env.E2E_BASE_URL||'http://127.0.0.1:8000'
  const key=process.env.E2E_INSTRUCTOR_SECRET
  if(!key)throw new Error('Set E2E_INSTRUCTOR_SECRET.')
  const context=await browser.newContext({viewport:{width:1440,height:1000}})
  // Classroom fallback: the browser may reach the local server, but no internet resources.
  await context.route('**/*',route=>new URL(route.request().url()).origin===new URL(base).origin?route.continue():route.abort())
  const page=await context.newPage()
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(`${base}/instructor`)
  await page.getByLabel('Instructor access key').fill(key)
  await page.getByRole('checkbox',{name:/Demonstration room/}).check()
  await page.getByRole('button',{name:'Create game room'}).click()
  await expect(page.locator('.demo-banner')).toContainText('15 simulated annotators')
  const saved=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('true-cost-session')!))
  page.on('dialog',dialog=>dialog.accept(saved.code))
  await expect(page.locator('.big-stats strong').first()).toHaveText('276')
  await expect(page.locator('.room-card')).toBeHidden()
  await page.getByRole('button',{name:'Start annotation'}).click()
  await page.getByRole('button',{name:'Begin training',exact:true}).click()
  await page.getByText('Demonstrate team investments & auditing',{exact:true}).click()
  await page.getByLabel('Simulated company',{exact:true}).selectOption('1')
  for(const title of ['Additional annotation','Dataset auditing']){
    await page.locator('.demo-controls .purchase-card').filter({has:page.getByRole('heading',{name:title,exact:true})}).getByRole('button').click()
  }
  await page.getByRole('button',{name:'Simulate pending annotations'}).click()
  await expect(page.getByText('10 additional scripted labels loaded.',{exact:true})).toBeVisible()
  await page.locator('.audit-post').first().getByRole('button',{name:'Open review'}).click()
  await page.locator('.audit-post').first().getByRole('button',{name:'Finalize allow'}).click()
  await expect(page.locator('.audit-post').first()).toContainText('Final team decision: allow')
  await page.getByRole('button',{name:'Train eligible teams'}).click()
  await expect(page.locator('.company-floor .model-saved')).toHaveCount(3)
  await page.getByRole('button',{name:'Compare models'}).click()
  await expect(page.locator('.confusion')).toHaveCount(3)
  await page.getByRole('button',{name:'Reveal the hidden infrastructure'}).click()
  await expect(page.getByRole('heading',{name:'Your AI was never alone.'})).toBeVisible()
  await expect(page.locator('.resource-disclosure')).toContainText('DEMONSTRATION')
  await page.getByRole('button',{name:'Presentation',exact:true}).click()
  await expect(page.getByRole('button',{name:'Exit presentation'})).toBeVisible()
  await page.getByRole('button',{name:/^Mineral extraction/}).click()
  await expect(page.locator('#node-detail')).toContainText('No quantity of mined material has been measured')
  await page.locator('.infrastructure').screenshot({path:'test-results/reveal-projector.png'})
  await page.getByRole('button',{name:'Classification & bias',exact:true}).click()
  await expect(page.locator('#node-detail').getByRole('heading',{name:'Classification choices'})).toBeVisible()
  await page.getByLabel('Explore company',{exact:true}).selectOption('1')
  await expect(page.getByRole('button',{name:/^Human annotators/})).toContainText('102 scripted labels')
  await page.getByRole('button',{name:'Reset room',exact:true}).click()
  await page.getByRole('button',{name:'Exit presentation'}).click()
  await expect(page.getByRole('heading',{name:'Your workforce is assembling.'})).toBeVisible()
  await expect(page.locator('.big-stats strong').first()).toHaveText('276')
  await expect(page.locator('.model-saved')).toHaveCount(0)
  expect(errors).toEqual([])
  await context.close()
})
